create function public.security_audit_write() returns trigger language plpgsql security definer set search_path=''
as $$
declare v_old jsonb; v_new jsonb; v_id text;
begin
 if tg_op<>'INSERT' then v_old:=to_jsonb(old); end if;
 if tg_op<>'DELETE' then v_new:=to_jsonb(new); end if;
 v_id:=coalesce(v_new->>'id',v_old->>'id');
 insert into public.audit_logs(actor_id,entity_type,entity_id,action,old_values,new_values,reason)
 values(auth.uid(),tg_table_name,v_id,lower(tg_op),v_old,v_new,
   coalesce(nullif(current_setting('portal.audit_reason',true),''),'Administrative '||lower(tg_op)));
 if tg_op='DELETE' then return old; end if;
 return new;
end $$;
create function public.security_audit_immutable() returns trigger language plpgsql set search_path=''
as $$ begin raise exception 'Audit history is immutable.'; end $$;
