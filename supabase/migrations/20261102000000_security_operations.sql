as $$ select floor_id from public.profiles where id=auth.uid() and employment_status='Active' $$;
create function public.security_can_see_employee(p_id uuid) returns boolean
language sql stable security definer set search_path='' as $$
 select public.security_role() is not null and (p_id=auth.uid()
   or public.security_role() in ('admin','director','asm')
   or (public.security_role()='supervisor' and exists
       (select 1 from public.profiles where id=p_id and shift_id=public.security_shift())))
$$;

